class DetailLevel(str, Enum):
    """Detail level for responses."""
    BRIEF = "brief"  # Use rollup summary directly
    DETAILED = "detailed"  # Full LLM synthesis
    COMPREHENSIVE = "comprehensive"  # Deep dive with snippets


class RoutePlan(BaseModel):
    """
    Plan for fast retrieval routing.
    
    Generated by LocalRouter or LLMRouter, this plan specifies
    which Cypher template to use and what parameters to pass.
    """
    
    route_id: RouteId = Field(
        ...,
        description="Route identifier mapping to a Cypher template"
    )
    
    confidence: float = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        description="Confidence in this routing decision"
    )
    
    # Time range filters
    time_range: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Time range for query (start_date, end_date, relative_days)"
    )
    
    start_date: Optional[date] = Field(
        default=None,
        description="Explicit start date"
    )
    
    end_date: Optional[date] = Field(
        default=None,
        description="Explicit end date"
    )
    
    relative_days: Optional[int] = Field(
        default=None,
        description="Relative days from today (e.g., 7 for last week)"
    )
    
    # Entity filters
    entities: Dict[str, List[str]] = Field(
        default_factory=dict,
        description="Entities to filter by (workgroups, topics, organizations, people)"
    )
    
    workgroups: List[str] = Field(
        default_factory=list,
        description="Workgroup IDs or names"
    )
    
    topics: List[str] = Field(
        default_factory=list,
        description="Topic names or IDs"
    )
    
    organizations: List[str] = Field(
        default_factory=list,
        description="Organization names or IDs"
    )
    
    people: List[str] = Field(
        default_factory=list,
        description="Person names or IDs"
    )
    
    category: Optional[str] = Field(
        default=None,
        description="Document category filter (press release, whitepaper, article, blog, newsletter, technical specification)"
    )
    
    exclude_meetings: Optional[bool] = Field(
        default=None,
        description="For event queries: exclude meetings and only return conferences/summits"
    )
    
    # User source membership filters (populated from user_source_memberships table)
    excluded_datasources: List[str] = Field(
        default_factory=list,
        description="Datasource IDs to hard-exclude from results (user has ignored these)"
    )

    preferred_datasources: List[str] = Field(
        default_factory=list,
        description="Datasource IDs to boost in results (user has joined these)"
    )

    # Response preferences
    detail_level: DetailLevel = Field(
        default=DetailLevel.DETAILED,
        description="Level of detail in response"
    )
    
    deep_dive: bool = Field(
        default=False,
        description="Whether to fetch document snippets for evidence"
    )
    
    # Metadata
    template_version: str = Field(
        default="1.0.0",
        description="Cypher template version for cache invalidation"
    )
    
    routing_method: str = Field(
        default="local",
        description="How route was determined: 'local' or 'llm'"
    )
    
    raw_query: str = Field(
        default="",
        description="Original user query for context"
    )
    
    class Config:
        """Pydantic config."""
        use_enum_values = True


class RouteResult(BaseModel):
    """Result from Cypher template execution."""
    
    route_id: RouteId
    
    # Raw results from Neo4j
    nodes: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Thin node results from Cypher query"
    )
    
    rollup: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Rollup node if available"
    )
    
    # Execution metadata
    execution_time_ms: int = Field(
        default=0,
        description="Cypher query execution time"
    )
    
    node_count: int = Field(
        default=0,
        description="Number of nodes returned"
    )
    
    cache_hit: bool = Field(
        default=False,
        description="Whether result came from cache"
    )


class DeepDiveResult(BaseModel):
    """Result from deep dive document retrieval."""
    
    snippets: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Document snippets with context"
    )
    
    total_tokens: int = Field(
        default=0,
        description="Total tokens in all snippets"
    )
    
    vector_search_time_ms: int = Field(
        default=0,
        description="Time spent on vector search"
    )
