    DECISIONS_BY_WORKGROUP = "decisions_by_workgroup"
    DECISIONS_BY_TOPIC = "decisions_by_topic"
    RECENT_DECISIONS = "recent_decisions"
    
    # Action items & Tasks
    ACTION_ITEMS_OPEN = "action_items_open"
    ACTION_ITEMS_BY_WORKGROUP = "action_items_by_workgroup"
    ACTION_ITEMS_BY_PERSON = "action_items_by_person"
    ACTION_ITEMS_OVERDUE = "action_items_overdue"
    ACTION_ITEMS_COMPLETED = "action_items_completed"
    
    # Topic & Content Discovery
